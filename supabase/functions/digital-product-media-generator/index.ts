async function adminUser(req:Request){
 const auth=req.headers.get("authorization")||"";
 if(auth.startsWith("Bearer ")){
  const {data:{user}}=await db.auth.getUser(auth.slice(7)); if(!user)return null;
  const {data:roles}=await db.from("user_roles").select("role").eq("user_id",user.id);
  const email=(user.email||"").toLowerCase();
  return email==="ceo@resofit.fit"||(roles||[]).some((r:any)=>["admin","moderator"].includes(String(r.role||"")))?user:null;
 }
 const internalKey=Deno.env.get("RESOFIT_FACTORY_INTERNAL_SECRET")||Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")||Deno.env.get("GEMINI_API_KEY")||"",ts=req.headers.get("x-resofit-factory-ts")||"",sig=req.headers.get("x-resofit-factory-signature")||"",action=req.headers.get("x-resofit-factory-action")||"",jobId=req.headers.get("x-resofit-factory-job")||"";
 const dispatchToken=req.headers.get("x-resofit-factory-dispatch-token")||"";
 if(dispatchToken&&jobId&&["start","poll"].includes(action)){
  const {data:dispatchJob}=await db.from("digital_product_factory_jobs").select("id,generation_spec").eq("id",jobId).maybeSingle();
  const gs:any=dispatchJob?.generation_spec||{};
  const expiry=Number(gs.dispatch_token_expires_at||0);
  if(dispatchJob&&gs.dispatch_token===dispatchToken&&expiry>=Date.now()){
   const cleaned={...gs};delete cleaned.dispatch_token;delete cleaned.dispatch_token_expires_at;
   await db.from("digital_product_factory_jobs").update({generation_spec:cleaned,updated_at:new Date().toISOString()}).eq("id",jobId);
   return ({id:"internal-one-time-dispatch",email:"internal-one-time-dispatch"} as any);
  }
 }
 if(!internalKey||!ts||!sig||!action||!jobId)return null;
 const age=Math.abs(Math.floor(Date.now()/1000)-Number(ts))*1000; if(!Number.isFinite(age)||age>300000)return null;
 const data=new TextEncoder().encode(ts+"."+action+"."+jobId);
 const key=await crypto.subtle.importKey("raw",new TextEncoder().encode(internalKey),{name:"HMAC",hash:"SHA-256"},false,["sign"]);
 const mac=await crypto.subtle.sign("HMAC",key,data),expected=Array.from(new Uint8Array(mac)).map(x=>x.toString(16).padStart(2,"0")).join("");
 return sig===expected?({id:"internal-factory-worker",email:"internal-factory-worker"} as any):null;
}
async function upload(path:string,bytes:Uint8Array,mime:string){
 const bucket=db.storage.from(BUCKET);
 let r=await bucket.upload(path,bytes,{contentType:mime,upsert:true});
 if(r.error){
  const created=await db.storage.createBucket(BUCKET,{public:true,fileSizeLimit:524288000});
  if(created.error&&!/already exists/i.test(created.error.message))throw created.error;
  r=await bucket.upload(path,bytes,{contentType:mime,upsert:true});
 }
 if(r.error)throw r.error;
 return bucket.getPublicUrl(path).data.publicUrl;
}
async function register(job:any,slot:any,bytes:Uint8Array,mime:string,sourceId:string){
 const path=`${job.product_sku}/v${job.version}/${slot.role}.${mime==="video/mp4"?"mp4":"png"}`;
 const url=await upload(path,bytes,mime);
 const video=mime==="video/mp4";
 const {data:asset,error}=await db.from("content_asset_registry").upsert({
  source_provider:"gemini_api",source_asset_id:sourceId,source_url:url,canonical_url:url,
  brand:"ResoFlex",campaign:"digital_product_factory",asset_type:video?"video":"image",mime_type:mime,
  rights_status:"gemini_api_generated",commercial_status:"factory_generated",qa_status:"pending",
  qa_reason:"Generated by production Digital Product Factory; existing ChatB2K/Gemini QA required.",
  content_pillar:"DIGITAL_PRODUCT",
  intelligence:{factory_job_id:job.id,product_sku:job.product_sku,role:slot.role,media_origin:video?"Google Gemini API / Veo 3.1":"Google Gemini API / Gemini 3.1 Flash Image",generation_version:job.version,canonical_destination:`https://www.resofit.fit/product/${job.generation_spec?.product?.handle??job.product_sku}`},
  verified_at:new Date().toISOString(),updated_at:new Date().toISOString()
 },{onConflict:"source_provider,source_asset_id"}).select("id,canonical_url,asset_type,qa_status").single();
 if(error)throw error;
 const {error:attachError}=await db.from("digital_product_factory_assets").upsert({job_id:job.id,content_asset_id:asset.id,role:slot.role,required:!!slot.required,status:"attached"},{onConflict:"job_id,content_asset_id,role"});
 if(attachError)throw attachError;
 return asset;
}
async function startVideo(key:string,slot:any){
 const r=await fetch(`${GEMINI_BASE}/models/${VIDEO_MODEL}:predictLongRunning`,{method:"POST",headers:{"x-goog-api-key":key,"content-type":"application/json"},body:JSON.stringify({instances:[{prompt:slot.prompt}],parameters:{aspectRatio:slot.aspect_ratio,durationSeconds:Number(slot.duration_seconds??8),resolution:"720p"}})});
 const b=await r.json();if(!r.ok||!b.name)throw new Error(`veo_submit_failed:${r.status}:${String(b?.error?.message||b?.message||"provider_request_rejected").slice(0,240)}`);return b.name;
}
async function generateImage(key:string,slot:any){
 const r=await fetch(`${GEMINI_BASE}/interactions`,{method:"POST",headers:{"x-goog-api-key":key,"content-type":"application/json"},body:JSON.stringify({model:IMAGE_MODEL,input:[{type:"text",text:slot.prompt}],response_format:{type:"image",mime_type:"image/png",aspect_ratio:slot.aspect_ratio,image_size:"2K"}})});
 const b=await r.json();if(!r.ok||!b?.output_image?.data)throw new Error(`image_generation_failed:${r.status}`);return Uint8Array.from(atob(b.output_image.data),c=>c.charCodeAt(0));
}
async function pollVideo(key:string,name:string){
 const r=await fetch(`${GEMINI_BASE}/${name}`,{headers:{"x-goog-api-key":key}});const b=await r.json();if(!r.ok)throw new Error("veo_poll_failed");if(!b.done)return null;if(b.error)throw new Error("veo_generation_failed");
 const uri=b?.response?.generateVideoResponse?.generatedSamples?.[0]?.video?.uri;if(!uri)throw new Error("veo_output_missing");
 const v=await fetch(uri,{headers:{"x-goog-api-key":key}});if(!v.ok)throw new Error("veo_download_failed");return new Uint8Array(await v.arrayBuffer());
}
async function automationKillReason(): Promise<{blocked:boolean;reason:string}> {
 const {data,error}=await db.from("chatb2k_control_plane").select("kill_switch_enabled,kill_switch_reason").eq("id",true).maybeSingle();
 if(error||!data)return {blocked:true,reason:"Control plane unavailable; automation paused"};
 return {blocked:data.kill_switch_enabled===true,reason:String(data.kill_switch_reason||"Orchestration globally paused")};
}
Deno.serve(async req=>{
 if(req.method==="OPTIONS")return new Response("ok",{headers:cors});
 try{
  const user=await adminUser(req);if(!user)return out({ok:false,error:"forbidden"},403);
  const body=await req.json().catch(()=>({}));const action=String(body.action||"status");const jobId=String(body.job_id||"");
  if(action==="start"){const gate=await automationKillReason();if(gate.blocked)return out({ok:false,error:"CHATB2K_GLOBAL_KILL_SWITCH_ACTIVE",reason:gate.reason},503);}
  const key=await factoryKey();
  if(!jobId)return out({ok:false,error:"job_id_required"},400);
  const {data:job,error}=await db.from("digital_product_factory_jobs").select("*").eq("id",jobId).maybeSingle();if(error||!job)return out({ok:false,error:"job_not_found"},404);
  const spec=structuredClone(job.generation_spec||{});
  if(action==="start"){
   for(const slot of spec.asset_slots||[]){
    if(slot.runtime?.status)continue;
    slot.runtime={status:"generating",started_at:new Date().toISOString(),model:slot.type==="video"?VIDEO_MODEL:IMAGE_MODEL};
    if(slot.type==="video"){slot.runtime.operation_name=await startVideo(key,slot);slot.runtime.status="submitted";}
    else{const bytes=await generateImage(key,slot);const asset=await register(job,slot,bytes,"image/png",`${job.id}:${slot.role}:v${job.version}`);slot.runtime={status:"completed",asset_id:asset.id};}
    await db.from("digital_product_factory_jobs").update({generation_spec:spec,status:"generating",updated_at:new Date().toISOString()}).eq("id",job.id);
   }
   return out({ok:true,status:"generating",generation_spec:spec});
  }
  if(action==="poll"){
   const results:any[]=[];
   for(const slot of spec.asset_slots||[]){
    if(slot.type!=="video"||slot.runtime?.status!=="submitted")continue;
    const bytes=await pollVideo(key,slot.runtime.operation_name);
    if(!bytes){results.push({role:slot.role,status:"pending"});continue;}
    const asset=await register(job,slot,bytes,"video/mp4",`${job.id}:${slot.role}:v${job.version}`);
    slot.runtime={status:"completed",asset_id:asset.id};results.push({role:slot.role,status:"completed",asset_id:asset.id});
   }
   const required=(spec.asset_slots||[]).filter((s:any)=>s.required);
   const completed=(spec.asset_slots||[]).filter((s:any)=>s.runtime?.status==="completed").length;
   const requiredComplete=required.every((s:any)=>s.runtime?.status==="completed");
   await db.from("digital_product_factory_jobs").update({generation_spec:spec,asset_count:completed,status:requiredComplete?"qa":"generating",updated_at:new Date().toISOString()}).eq("id",job.id);
   return out({ok:true,completed,total:(spec.asset_slots||[]).length,results});
  }
  return out({ok:true,status:job.status,generation_spec:spec,assets:job.asset_count,approved:job.approved_asset_count});
 }catch(e){const message=e instanceof Error?e.message:"factory_error";const status=/:(429):/.test(message)?429:500;return out({ok:false,error:message,retryable:status===429},status)}
});